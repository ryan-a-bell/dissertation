def print_phase(phase_num: int, title: str) -> None:
    """Print a phase header."""
    print(f"\n{'='*80}")
    print(f"  PHASE {phase_num}: {title}")
    print(f"{'='*80}\n")


def print_success(msg: str) -> None:
    print(f"  [PASS] {msg}")


def print_fail(msg: str) -> None:
    print(f"  [FAIL] {msg}")


def build_mcq_prompt(row: pd.Series) -> str:
    """Build MCQ prompt in lm-eval format."""
    return (
        "Given the following question and four candidate answers (A, B, C and D), "
        "choose the best answer. Your response must consist solely of the single "
        "letter corresponding to the best answer, chosen from one of A, B, C or D. "
        "Any response other than a single letter (A, B, C, or D) will be considered "
        f"invalid.\nQuestion: {row['question']}\n"
        f"A. {row['choiceA']}\nB. {row['choiceB']}\n"
        f"C. {row['choiceC']}\nD. {row['choiceD']}\nAnswer:"
    )


def build_osq_prompt(row: pd.Series) -> str:
    """Build OSQ prompt in lm-eval format."""
    prompt_field = row.get("osq_prompt", row.get("question", ""))
    return (
        "Given the following question, answer it to the best of your ability. "
        "Your response should generally be between 2 and 4 sentences, but may "
        "be longer if a more detailed solution is appropriate.\n"
        f"{prompt_field}\nAnswer:"
    )


def write_lm_eval_results(
    output_dir: Path,
    task_name: str,
    accuracy: float,
    n_samples: int,
    timestamp: str,
) -> Path:
    """Write a lm-eval compatible results.json file."""
    output_dir.mkdir(parents=True, exist_ok=True)

    results = {
        "results": {
            task_name: {
                "alias": task_name,
                "exact_match,strict-match": accuracy,
                "exact_match_stderr,strict-match": 0.0,
            }
        },
        "group_subtasks": {task_name: []},
        "configs": {
            task_name: {
                "task": task_name,
                "output_type": "generate_until",
                "num_fewshot": 0,
                "metric_list": [
                    {
                        "metric": "exact_match",
                        "aggregation": "mean",
                        "higher_is_better": True,
                    }
                ],
                "metadata": {
                    "version": 1.0,
                    "model": MODEL_NAME,
                },
            }
        },
        "versions": {task_name: 1.0},
        "n-shot": {task_name: 0},
        "higher_is_better": {task_name: {"exact_match": True}},
        "n-samples": {
            task_name: {"original": 1144, "effective": n_samples}
        },
        "config": {
            "model": "anthropic-chat-completions",
            "model_args": f"model={MODEL_NAME}",
            "batch_size": 1,
            "batch_sizes": [],
            "device": None,
            "limit": float(n_samples),
        },
        "model_name": MODEL_NAME,
        "model_name_sanitized": MODEL_NAME_SANITIZED,
        "lm_eval_version": "0.4.9.1",
        "date": time.time(),
        "total_evaluation_time_seconds": "0.0",
    }

    results_path = output_dir / f"results_{timestamp}.json"
    with open(results_path, "w") as f:
        json.dump(results, f, indent=2)

    return results_path


def write_lm_eval_samples(
    output_dir: Path,
    task_name: str,
    samples: list[dict],
    timestamp: str,
) -> Path:
    """Write a lm-eval compatible samples.jsonl file."""
    output_dir.mkdir(parents=True, exist_ok=True)

    samples_path = output_dir / f"samples_{task_name}_{timestamp}.jsonl"
    with open(samples_path, "w") as f:
        for sample in samples:
            f.write(json.dumps(sample) + "\n")

    return samples_path


