def main() -> int:
    results_summary = {}
    start_time = time.time()

    print("\n" + "#" * 80)
    print("  METAEVAL FULL PIPELINE TEST")
    print(f"  Inference Model: {MODEL_NAME}")
    print(f"  Judge Model:     {MODEL_NAME}")
    print(f"  Questions:       {N_QUESTIONS}")
    print(f"  Date:            {datetime.now().isoformat()}")
    print("#" * 80)

    # -----------------------------------------------------------------------
    # PHASE 1-3: Load existing data
    # -----------------------------------------------------------------------
    print_phase(1, "LOAD BENCHMARK DATA (Phases 1-3)")

    # Load MCQ data
    mcq_df = pd.read_csv(MCQ_CSV)
    mcq_4 = mcq_df[mcq_df["Question ID"].isin(range(1, N_QUESTIONS + 1))].copy()
    print_success(f"Loaded MCQ benchmark: {len(mcq_df)} total, {len(mcq_4)} selected")

    # Load OSQ data
    osq_df = pd.read_csv(OSQ_CSV)
    osq_4 = osq_df[osq_df["Question ID"].isin(range(1, N_QUESTIONS + 1))].copy()
    print_success(f"Loaded OSQ data: {len(osq_df)} total, {len(osq_4)} selected")

    # Load variant data
    variant_dfs = {}
    for variant in ["a", "b", "c", "d"]:
        vdf = pd.read_csv(VARIANT_DIR / f"sysengbench_{variant}.csv")
        variant_dfs[variant] = vdf[
            vdf["Question ID"].isin(range(1, N_QUESTIONS + 1))
        ].copy()
        print_success(
            f"Loaded variant {variant.upper()}: "
            f"{len(vdf)} total, {len(variant_dfs[variant])} selected"
        )

    results_summary["phase_1_3"] = "PASS"

    # Print sample question
    print(f"\n  Sample Question (ID=1):")
    row = mcq_4.iloc[0]
    print(f"    {row['question'][:80]}...")
    print(f"    Correct answer: {row['answer']}")

    # -----------------------------------------------------------------------
    # PHASE 4: Inference (agent-generated, write lm-eval format)
    # -----------------------------------------------------------------------
    print_phase(4, "INFERENCE (Opus 4.6 Agent Responses)")

    # --- MCQ Inference ---
    print("  --- MCQ Inference (4 variants x 4 questions = 16 responses) ---\n")

    mcq_results_by_variant = {}

    for variant in ["a", "b", "c", "d"]:
        vdf = variant_dfs[variant]
        task_name = f"sysengbench-{variant}" if variant != "a" else "sysengbench"
        # Use sysengbench (no suffix) for variant a to match lm-eval convention
        # Actually lm-eval uses sysengbench-a for variant a too in our setup
        task_name = f"sysengbench-{variant}"

        samples = []
        correct_count = 0

        for idx, (_, row) in enumerate(vdf.iterrows()):
            qid = row["Question ID"]
            answer = MCQ_ANSWERS[variant][qid]
            target = row["answer"]
            is_correct = answer.strip().upper() == target.strip().upper()
            if is_correct:
                correct_count += 1

            prompt_text = build_mcq_prompt(row)

            sample = {
                "doc_id": idx,
                "doc": {
                    "Question ID": int(qid),
                    "Tags": row.get("Tags", ""),
                    "INCOSE Handbook Category": row.get(
                        "INCOSE Handbook Category", ""
                    ),
                    "question": row["question"],
                    "choiceA": row["choiceA"],
                    "choiceB": row["choiceB"],
                    "choiceC": row["choiceC"],
                    "choiceD": row["choiceD"],
                    "answer": target,
                    "label": int(row.get("label", 0)),
                    "Justification": row.get("Justification", ""),
                },
                "target": target,
                "arguments": {
                    "gen_args_0": {
                        "arg_0": json.dumps(
                            [{"content": prompt_text, "role": "user"}]
                        ),
                        "arg_1": {
                            "until": [],
                            "max_gen_toks": 10,
                            "temperature": 0.0,
                        },
                    }
                },
                "resps": [[answer]],
                "filtered_resps": [answer],
                "filter": "strict-match",
                "metrics": ["exact_match"],
                "doc_hash": "",
                "prompt_hash": "",
                "target_hash": "",
                "exact_match": 1.0 if is_correct else 0.0,
            }
            samples.append(sample)

        accuracy = correct_count / len(samples) if samples else 0.0
        mcq_results_by_variant[variant] = {
            "accuracy": accuracy,
            "correct": correct_count,
            "total": len(samples),
            "samples": samples,
        }

        # Write lm-eval output
        model_dir = OUTPUT_DIR / task_name / MODEL_NAME_SANITIZED
        write_lm_eval_results(model_dir, task_name, accuracy, len(samples), TIMESTAMP)
        write_lm_eval_samples(model_dir, task_name, samples, TIMESTAMP)

        status = "PASS" if accuracy == 1.0 else "PARTIAL"
        print_success(
            f"Variant {variant.upper()}: {correct_count}/{len(samples)} correct "
            f"({accuracy:.0%}) [{status}]"
        )

    # --- OSQ Inference ---
    print("\n  --- OSQ Inference (4 open-ended responses) ---\n")

    osq_samples = []
    for idx, (_, row) in enumerate(osq_4.iterrows()):
        qid = row["Question ID"]
        response = OSQ_RESPONSES[qid]
        prompt_text = build_osq_prompt(row)

        sample = {
            "doc_id": idx,
            "doc": {
                "Question ID": int(qid),
                "Tags": row.get("Tags", ""),
                "INCOSE Handbook Category": row.get(
                    "INCOSE Handbook Category", ""
                ),
                "question": row["question"],
                "choiceA": row.get("choiceA", ""),
                "choiceB": row.get("choiceB", ""),
                "choiceC": row.get("choiceC", ""),
                "choiceD": row.get("choiceD", ""),
                "answer": row.get("answer", ""),
                "label": int(row.get("label", 0)),
                "Justification": row.get("Justification", ""),
                "osq_prompt": row.get("osq_prompt", ""),
                "expected_answer": row.get("expected_answer", ""),
                "full_credit_criteria": row.get("full_credit_criteria", ""),
                "partial_credit_criteria": row.get(
                    "partial_credit_criteria", ""
                ),
                "no_credit_criteria": row.get("no_credit_criteria", ""),
                "blooms_level": row.get("blooms_level", ""),
                "blooms_justification": row.get("blooms_justification", ""),
            },
            "target": row.get("expected_answer", ""),
            "arguments": {
                "gen_args_0": {
                    "arg_0": json.dumps(
                        [{"content": prompt_text, "role": "user"}]
                    ),
                    "arg_1": {
                        "until": [],
                        "max_gen_toks": 500,
                        "temperature": 0.0,
                    },
                }
            },
            "resps": [[response]],
            "filtered_resps": [response],
            "filter": "none",
            "metrics": ["exact_match"],
            "doc_hash": "",
            "prompt_hash": "",
            "target_hash": "",
            "exact_match": 0.0,  # OSQ exact match is always 0 (needs judge)
        }
        osq_samples.append(sample)
        print_success(f"Q{qid} response ({len(response)} chars): {response[:60]}...")

    # Write OSQ lm-eval output
    osq_model_dir = OUTPUT_DIR / "sysengbench-osq" / MODEL_NAME_SANITIZED
    write_lm_eval_results(osq_model_dir, "sysengbench-osq", 0.0, len(osq_samples), TIMESTAMP)
    write_lm_eval_samples(osq_model_dir, "sysengbench-osq", osq_samples, TIMESTAMP)

    results_summary["phase_4"] = "PASS"

    # -----------------------------------------------------------------------
    # PHASE 4.5: Verify lm-eval output can be parsed by metaeval harness
    # -----------------------------------------------------------------------
    print("\n  --- Verifying lm-eval output format (LMEvalParser) ---\n")

    from metaeval.harness import LMEvalParser

    # Test MCQ parsing
    for variant in ["a", "b", "c", "d"]:
        task_name = f"sysengbench-{variant}"
        model_dir = OUTPUT_DIR / task_name / MODEL_NAME_SANITIZED
        parser = LMEvalParser(model_dir)
        run = parser.parse()
        print_success(
            f"LMEvalParser read variant {variant.upper()}: "
            f"task={run.task}, model={run.model}, "
            f"format={run.format}, samples={run.n_samples}, "
            f"accuracy={run.accuracy:.0%}"
        )

    # Test OSQ parsing
    parser = LMEvalParser(osq_model_dir)
    run = parser.parse()
    osq_results_parsed = parser.to_osq_results()
    print_success(
        f"LMEvalParser read OSQ: task={run.task}, "
        f"format={run.format}, samples={run.n_samples}"
    )
    for r in osq_results_parsed:
        print(f"    OSQ Q{r.question_id}: response={r.model_response[:50]}...")

    # -----------------------------------------------------------------------
    # PHASE 5: Judging (agent-generated, parsed by metaeval scorer)
    # -----------------------------------------------------------------------
    print_phase(5, "LLM-AS-A-JUDGE (Opus 4.6 Agent Evaluations)")

    from metaeval.judge.scorer import parse_judgment

    JUDGED_DIR.mkdir(parents=True, exist_ok=True)
    judged_path = JUDGED_DIR / "judged.jsonl"

    judged_results = []

    for osq_result in osq_results_parsed:
        qid = osq_result.question_id
        raw_judgment = JUDGE_RESPONSES[qid]

        # Parse using metaeval's scorer
        parsed = parse_judgment(raw_judgment)

        judgment_record = {
            "question_id": qid,
            "model": MODEL_NAME_SANITIZED,
            "judge_model": MODEL_NAME,
            "prompt_style": "multi_dimensional",
            "scores": parsed.scores.to_dict() if parsed.scores else None,
            "total_score": parsed.total_score,
            "justification": parsed.justification,
            "credit_level": parsed.credit_level,
            "parse_success": parsed.parse_success,
            "parse_errors": parsed.parse_errors,
            "from_cache": False,
        }
        judged_results.append(judgment_record)

        status = "PASS" if parsed.parse_success else "FAIL"
        if parsed.scores:
            dims = parsed.scores.to_dict()
            dim_str = ", ".join(f"{k[:4]}={v}" for k, v in dims.items())
            print_success(
                f"Q{qid}: total={parsed.total_score}/100 "
                f"credit={parsed.credit_level} [{status}]"
            )
            print(f"         Dimensions: {dim_str}")
        else:
            print_fail(
                f"Q{qid}: parse failed - {parsed.parse_errors}"
            )

    # Write judged output
    with open(judged_path, "w") as f:
        for record in judged_results:
            f.write(json.dumps(record) + "\n")

    all_parsed = all(r["parse_success"] for r in judged_results)
    results_summary["phase_5"] = "PASS" if all_parsed else "FAIL"
    print(f"\n  Judged {len(judged_results)} responses -> {judged_path}")
    print(f"  All parsed successfully: {all_parsed}")

    # -----------------------------------------------------------------------
    # PHASE 6a: Position Bias Analysis
    # -----------------------------------------------------------------------
    print_phase(6, "ANALYSIS")

    print("  --- 6a: Position Bias Analysis ---\n")

    from metaeval.bias.detection import PositionBiasAnalyzer

    # Build DataFrame from MCQ results
    bias_rows = []
    for variant, data in mcq_results_by_variant.items():
        for sample in data["samples"]:
            bias_rows.append({
                "model": MODEL_NAME_SANITIZED,
                "variant": variant.upper(),
                "question_id": sample["doc"]["Question ID"],
                "is_correct": int(sample["exact_match"]),
            })

    bias_df = pd.DataFrame(bias_rows)
    print_success(f"Built bias DataFrame: {len(bias_df)} rows")
    print(f"    Columns: {list(bias_df.columns)}")
    print(f"    Models: {bias_df['model'].unique().tolist()}")
    print(f"    Variants: {sorted(bias_df['variant'].unique().tolist())}")

    try:
        analyzer = PositionBiasAnalyzer(bias_df)
        bias_reports = analyzer.analyze_all_models()

        for model, report in bias_reports.items():
            acc = report.accuracy_by_position
            print_success(
                f"Model: {model}\n"
                f"         Overall accuracy: {report.overall_accuracy:.0%}\n"
                f"         By position: "
                + ", ".join(f"{k}={v:.0%}" for k, v in sorted(acc.items()))
                + f"\n         Significant bias: {report.has_significant_bias}"
            )

        results_summary["phase_6a_bias"] = "PASS"
    except Exception as e:
        print_fail(f"Bias analysis failed: {e}")
        import traceback
        traceback.print_exc()
        results_summary["phase_6a_bias"] = f"FAIL: {e}"

    # -----------------------------------------------------------------------
    # PHASE 6b: MCQ vs OSQ Comparison
    # -----------------------------------------------------------------------
    print("\n  --- 6b: MCQ vs OSQ Format Comparison ---\n")

    from metaeval.compare.analysis import FormatComparator

    # Build comparison DataFrame
    # MCQ score = average accuracy across variants per question
    mcq_scores = {}
    for variant, data in mcq_results_by_variant.items():
        for sample in data["samples"]:
            qid = sample["doc"]["Question ID"]
            if qid not in mcq_scores:
                mcq_scores[qid] = []
            mcq_scores[qid].append(sample["exact_match"])

    compare_rows = []
    for qid in range(1, N_QUESTIONS + 1):
        mcq_avg = np.mean(mcq_scores.get(qid, [0.0]))
        # Find matching judged result
        osq_score = 0.0
        for jr in judged_results:
            if jr["question_id"] == qid:
                osq_score = float(jr["total_score"])
                break

        compare_rows.append({
            "model": MODEL_NAME_SANITIZED,
            "question_id": qid,
            "mcq_score": mcq_avg,
            "osq_score": osq_score,
        })

    compare_df = pd.DataFrame(compare_rows)
    print_success(f"Built comparison DataFrame: {len(compare_df)} rows")
    print(f"    MCQ scores: {compare_df['mcq_score'].tolist()}")
    print(f"    OSQ scores: {compare_df['osq_score'].tolist()}")

    try:
        comparator = FormatComparator(compare_df)
        compare_reports = comparator.analyze_all_models()

        for model, report in compare_reports.items():
            pearson = report.correlations.get("pearson")
            pearson_str = (
                f"{pearson.coefficient:.3f}" if pearson else "N/A"
            )
            print_success(
                f"Model: {model}\n"
                f"         MCQ accuracy: {report.mcq_accuracy:.0%}\n"
                f"         OSQ normalized: {report.osq_normalized:.0%}\n"
                f"         Pearson correlation: {pearson_str}\n"
                f"         N questions: {report.n_questions}"
            )

        results_summary["phase_6b_compare"] = "PASS"
    except Exception as e:
        print_fail(f"Comparison analysis failed: {e}")
        import traceback
        traceback.print_exc()
        results_summary["phase_6b_compare"] = f"FAIL: {e}"

    # -----------------------------------------------------------------------
    # FINAL SUMMARY
    # -----------------------------------------------------------------------
    elapsed = time.time() - start_time

    print(f"\n{'#'*80}")
    print("  PIPELINE TEST SUMMARY")
    print(f"{'#'*80}\n")

    all_pass = True
    for phase, status in results_summary.items():
        indicator = "[PASS]" if status == "PASS" else "[FAIL]"
        if status != "PASS":
            all_pass = False
        print(f"  {indicator} {phase}: {status}")

    print(f"\n  Total time: {elapsed:.1f}s")
    print(f"  Output directory: {OUTPUT_DIR}")
    print(f"  Judged directory: {JUDGED_DIR}")

    # List output files
    print(f"\n  Generated files:")
    for p in sorted(OUTPUT_DIR.rglob("*")):
        if p.is_file():
            print(f"    {p.relative_to(TEST_DIR)}")
    for p in sorted(JUDGED_DIR.rglob("*")):
        if p.is_file():
            print(f"    {p.relative_to(TEST_DIR)}")

    if all_pass:
        print(f"\n  RESULT: ALL PHASES PASSED")
    else:
        print(f"\n  RESULT: SOME PHASES FAILED")

    print(f"{'#'*80}\n")

    return 0 if all_pass else 1


